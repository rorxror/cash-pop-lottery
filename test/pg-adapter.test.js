'use strict';
/* v15 Postgres adapter tests: translatePg is pure and always runs; the live
   round-trip runs only when PG_TEST_URL (or DATABASE_URL) points at a real
   Postgres — otherwise it is skipped, never failed. */
const test = require('node:test');
const assert = require('node:assert');
const { translatePg } = require('../lib/db');

test('translatePg: numbers placeholders in order', () => {
  assert.strictEqual(
    translatePg('SELECT * FROM users WHERE email = ? AND status = ?'),
    'SELECT * FROM users WHERE email = $1 AND status = $2');
});

test('translatePg: leaves ? inside literals, identifiers and comments alone', () => {
  assert.strictEqual(
    translatePg("SELECT 'a?b', \"c?d\" FROM t WHERE x = ? -- why?\n/* ? */ AND y = ?"),
    "SELECT 'a?b', \"c?d\" FROM t WHERE x = $1 -- why?\n/* ? */ AND y = $2");
});

test('translatePg: escaped quotes do not end a literal', () => {
  assert.strictEqual(
    translatePg("SELECT * FROM t WHERE a = 'it''s ?' AND b = ?"),
    "SELECT * FROM t WHERE a = 'it''s ?' AND b = $1");
});

const LIVE_URL = process.env.PG_TEST_URL || process.env.DATABASE_URL || '';
test('postgres live round-trip (skipped without PG_TEST_URL/DATABASE_URL)', async (t) => {
  if (!LIVE_URL) { t.skip('no PG_TEST_URL/DATABASE_URL'); return; }
  const { openDB } = require('../lib/db');
  process.env.DATABASE_URL = LIVE_URL;
  process.env.DB_DRIVER = 'postgres';
  const { db } = openDB();
  await db.execScript(`
    CREATE TABLE IF NOT EXISTS pg_adapter_probe (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, balance BIGINT NOT NULL DEFAULT 0);
    DELETE FROM pg_adapter_probe;`);
  // insert returns id
  const ins = await db.run('INSERT INTO pg_adapter_probe (balance) VALUES (?)', [1000]);
  assert.ok(ins.id > 0, 'insert returns an id');
  // guarded UPDATE: overdraft must not apply (changes 0), like the ledger guard
  const over = await db.run('UPDATE pg_adapter_probe SET balance = balance + ? WHERE id = ? AND balance + ? >= 0', [-2000, ins.id, -2000]);
  assert.strictEqual(over.changes, 0);
  const ok = await db.run('UPDATE pg_adapter_probe SET balance = balance + ? WHERE id = ? AND balance + ? >= 0', [500, ins.id, 500]);
  assert.strictEqual(ok.changes, 1);
  const row = await db.get('SELECT balance FROM pg_adapter_probe WHERE id = ?', [ins.id]);
  assert.strictEqual(row.balance, 1500);
  // COUNT(*) arrives as a JS number (int8 parser), like SQLite/MySQL
  const c = await db.get('SELECT COUNT(*) AS n FROM pg_adapter_probe');
  assert.strictEqual(typeof c.n, 'number');
  assert.strictEqual(c.n, 1);
  // transaction rollback
  await assert.rejects(db.transaction(async (tx) => {
    await tx.run('INSERT INTO pg_adapter_probe (balance) VALUES (?)', [5]);
    throw new Error('boom');
  }));
  const c2 = await db.get('SELECT COUNT(*) AS n FROM pg_adapter_probe');
  assert.strictEqual(c2.n, 1);
  await db.execScript('DROP TABLE pg_adapter_probe;');
  await db.close();
});
